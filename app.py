# ----------------------------------------------------------------------
# HTTP server
# ----------------------------------------------------------------------
class Handler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def _send(self, code, body, ctype="application/json"):
        data = body.encode() if isinstance(body, str) else body
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            self._send(200, PAGE, "text/html; charset=utf-8")
        elif self.path == "/api/health":
            self._send(200, json.dumps({"llm": llm_available(), "faqs": len(FAQS)}))
        else:
            self._send(404, json.dumps({"error": "not found"}))

    def do_POST(self):
        if self.path != "/api/ask":
            self._send(404, json.dumps({"error": "not found"}))
            return
        length = int(self.headers.get("Content-Length", 0))
        try:
            message = json.loads(self.rfile.read(length).decode())["message"]
        except Exception:
            self._send(400, json.dumps({"error": "bad request"}))
            return

        # Try live LLM first (LM Studio), fall back to the built-in knowledge base
        if llm_available():
            try:
                self._send(200, json.dumps({"answer": llm_answer(message), "source": "llm"}))
                return
            except Exception:
                pass  # fall through to FAQ matching

        best, score = match_faq(message)
        if best and score >= 2:
            self._send(200, json.dumps({"answer": best["a"], "source": "faq",
                                        "matched": best["q"]}))
        else:
            self._send(200, json.dumps({"answer": FALLBACK, "source": "fallback"}))


