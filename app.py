def normalize(text):
    text = re.sub(r"[^\w\s]", " ", text.lower())
    return [w for w in text.split() if w and w not in STOPWORDS]


def match_faq(message):
    msg_words = set(normalize(message))
    msg_text = " ".join(normalize(message))
    best, best_score = None, 0
    for f in FAQS:
        kw_hits = sum(1 for kw in f["kw"] if kw in msg_text)
        q_words = set(normalize(f["q"]))
        overlap = len(msg_words & q_words)
        score = kw_hits * 3 + overlap
        if score > best_score:
            best, best_score = f, score
    return best, best_score


def llm_available():
    try:
        req = urllib.request.Request(f"{LLM_BASE_URL}/models", headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=2):
            return True
    except Exception:
        return False


def llm_answer(message):
    body = json.dumps({
        "model": "local-model",
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": message},
        ],
        "temperature": 0.4,
        "max_tokens": 600,
    }).encode()
    req = urllib.request.Request(
        f"{LLM_BASE_URL}/chat/completions", data=body,
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=120) as resp:
        data = json.loads(resp.read().decode())
    return data["choices"][0]["message"]["content"].strip()


